/*
 * Populate the Theme picker using the validated registry.
 */
function renderThemeOptions() {
  const selector = ui.themeSelect;

  selector.replaceChildren();

  themes.forEach((theme) => {
    if (!validateThemeDefinition(theme)) {
      throw new Error(
        "The trusted theme registry contains an invalid theme definition.",
      );
    }

    const option = document.createElement("option");
    option.value = theme.id;
    option.textContent = theme.name;

    selector.appendChild(option);
  });

  const selectedTheme = getTheme(state.themeId);

  if (!validateThemeDefinition(selectedTheme)) {
    throw new Error(`Unknown or invalid initial theme: ${state.themeId}`);
  }

  selector.value = selectedTheme.id;
}

/*
 * Return the selected checkbox values for one builder option
 * group.
 *
 * Restricting accepted group names prevents arbitrary CSS
 * selectors from being constructed from caller input.
 */
function getSelectedOptionValues(name) {
  if (name !== "edition" && name !== "category") {
    throw new Error(`Unsupported option group requested: ${name}`);
  }

  const selected = [
    ...document.querySelectorAll(`input[name="${name}"]:checked`),
  ].map((input) => input.value);

  const records = name === "edition" ? state.editions : state.categories;

  const allowedIds = new Set(
    records.filter((record) => record.active).map((record) => record.id),
  );

  selected.forEach((value) => {
    if (!allowedIds.has(value)) {
      throw new Error(`Unsupported ${name} selection: ${value}`);
    }
  });

  return selected;
}

