/*
 * Create one safely rendered checkbox option.
 */
function createCheckboxOption({ name, value, labelText, checked }) {
  const label = document.createElement("label");
  label.className = "option";

  const input = document.createElement("input");
  input.type = "checkbox";
  input.name = name;
  input.value = value;
  input.checked = checked;

  const text = document.createElement("span");
  text.textContent = labelText;

  label.append(input, text);

  return label;
}

/*
 * Populate the active edition and category choices from the
 * validated catalogs.
 *
 * The first active edition is selected initially, while all
 * active categories are selected.
 */
function renderOptions() {
  const editionContainer = ui.editionOptions;

  const categoryContainer = ui.categoryOptions;

  editionContainer.replaceChildren();
  categoryContainer.replaceChildren();

  state.editions
    .filter((edition) => edition.active)
    .forEach((edition, index) => {
      editionContainer.appendChild(
        createCheckboxOption({
          name: "edition",
          value: edition.id,
          labelText: edition.name,
          checked: index === 0,
        }),
      );
    });

  state.categories
    .filter((category) => category.active)
    .forEach((category) => {
      categoryContainer.appendChild(
        createCheckboxOption({
          name: "category",
          value: category.id,
          labelText: `${category.icon} ${category.name}`,
          checked: true,
        }),
      );
    });
}

