function renderThemeOptions() {
  const selector = ui.themeSelect;

  selector.replaceChildren();

  themes.forEach((theme) => {
    if (!validateThemeDefinition(theme)) {
      throw new Error(
        "The trusted theme registry contains an invalid theme definition.",
      );
    }

    const option = document.createElement("option");
    option.value = theme.id;
    option.textContent = theme.name;

    selector.appendChild(option);
  });

  const selectedTheme = getTheme(state.themeId);

  if (!validateThemeDefinition(selectedTheme)) {
    throw new Error(`Unknown or invalid initial theme: ${state.themeId}`);
  }

  selector.value = selectedTheme.id;
}

/*
 * Return the selected checkbox values for one builder option
 * group.
 *
 * Restricting accepted group names prevents arbitrary CSS
 * selectors from being constructed from caller input.
 */
function getSelectedOptionValues(name) {
  if (name !== "edition" && name !== "category") {
    throw new Error(`Unsupported option group requested: ${name}`);
  }

  const selected = [
    ...document.querySelectorAll(`input[name="${name}"]:checked`),
  ].map((input) => input.value);

  const records =
    name === "edition" ? state.catalog.editions : state.catalog.categories;

  const allowedIds = new Set(
    records.filter((record) => record.active).map((record) => record.id),
  );

  selected.forEach((value) => {
    if (!allowedIds.has(value)) {
      throw new Error(`Unsupported ${name} selection: ${value}`);
    }
  });

  return selected;
}

/*
 * Refresh live builder statistics from the current validated
 * catalog and content selections.
 */
function renderBuilderSelectionSummary() {
  const editions = getSelectedOptionValues("edition");
  const categories = getSelectedOptionValues("category");

  const eligibleCards = getEligibleCards(editions, categories);

  ui.availableCardCount.textContent = String(eligibleCards.length);
  ui.selectedEditionCount.textContent = String(editions.length);
  ui.selectedCategoryCount.textContent = String(categories.length);

  let requested = Number(ui.deckSizeInput.value);

  if (!Number.isInteger(requested) || requested < 1) {
    requested = 0;
  }

  const hasShortage = requested > eligibleCards.length;

  ui.availableCardCount.classList.toggle(
    "builder-summary-warning",
    hasShortage,
  );
  ui.builderSelectionSummary.classList.toggle(
    "builder-summary-shortage",
    hasShortage,
  );
}

/* ---------------------------------------------------------
 * Generation input validation
 * --------------------------------------------------------- */

/*
 * Require a whole-number playable-card count within the
 * application limit.
 */
function validateDeckSize(rawValue) {
  const size = Number(rawValue);

  if (!Number.isInteger(size)) {
    throw new TypeError("Deck size must be a whole number.");
  }

  if (size < 1 || size > LIMITS.maxDeckSize) {
    throw new RangeError(
      `Deck size must be between 1 and ${LIMITS.maxDeckSize}.`,
    );
  }

  return size;
}

/*
 * Normalize the generation seed.
 *
 * An empty value falls back to the demonstration seed so
 * generation remains deterministic.
 */
function validateSeed(rawSeed) {
  const normalized = typeof rawSeed === "string" ? rawSeed.trim() : "";

  const seed = normalized || "discussion-forge";

  if (seed.length > LIMITS.maxSeedLength) {
    throw new RangeError(
      `Seed cannot exceed ${LIMITS.maxSeedLength} characters.`,
    );
  }

  return seed;
}

