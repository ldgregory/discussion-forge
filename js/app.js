/* ---------------------------------------------------------
 * Deterministic deck identity
 * --------------------------------------------------------- */

/*
 * Create the canonical fingerprint and human-readable Deck ID
 * for a generated playable deck.
 *
 * Set-like configuration arrays are sorted, while card order
 * is preserved because permanent deck position is meaningful.
 */
async function createDeckIdentity({
  seed,
  editions,
  categories,
  requestedCardCount,
  cards,
}) {
  const identityPayload = {
    identity_version: DECK_IDENTITY_VERSION,
    generator_version: GENERATOR_VERSION,
    catalog_version: CATALOG_VERSION,
    seed,
    editions: [...editions].sort(),
    categories: [...categories].sort(),
    requested_card_count: requestedCardCount,

    /*
     * Ordered card identities make the fingerprint
     * describe the actual playable deck.
     */
    cards: cards.map((card) => ({
      card_uuid: card.card_uuid,
      content_version: card.content_version,
    })),
  };

  /*
   * Property order is intentionally fixed above, and
   * set-like arrays are sorted before serialization.
   */
  const canonicalPayload = JSON.stringify(identityPayload);

  const digest = await sha256Bytes(canonicalPayload);

  const fingerprint = bytesToHex(digest);

  const deckId = encodeBase32(digest).slice(0, HUMAN_DECK_ID_LENGTH);

  /*
   * Return both machine-readable and human-readable identities.
   */
  return {
    deckId,
    fingerprint,
    identityPayload,
  };
}

/*
 * Return true when a card is playable for the selected
 * editions and categories.
 *
 * A playable card must be active, approved, and associated
 * with at least one selected edition and one selected
 * category.
 */
function cardMatchesSelection(card, editions, categories) {
  return (
    card.active &&
    card.status === "approved" &&
    card.editions.some((editionId) => editions.includes(editionId)) &&
    card.categories.some((categoryId) => categories.includes(categoryId))
  );
}

/*
 * Build the manifest describing one generated deck.
 *
 * This preserves the generation configuration, deterministic
 * identity fields, and immutable card-content snapshots used
 * to identify or reproduce the deck.
 */
function buildManifest({
  deckUuid,
  deckId,
  fingerprint,
  seed,
  editions,
  categories,
  requested,
  generated,
}) {
  return {
    deck_uuid: deckUuid,
    deck_id: deckId,
    deck_fingerprint: fingerprint,
    deck_identity_version: DECK_IDENTITY_VERSION,

    generated_at: new Date().toISOString(),

    seed,

    generator_version: GENERATOR_VERSION,

    catalog_version: CATALOG_VERSION,

    configuration: {
      editions: [...editions],
      categories: [...categories],
      theme: state.themeId,
      requested_card_count: requested,
      playable_card_count: generated.length,
    },

    cards: generated.map((card) => ({
      deck_position: card.deck_position,

      card_uuid: card.card_uuid,

      content_version: card.content_version,

      content_snapshot: {
        prompt: card.content.prompt,

        instruction: card.content.instruction,
      },
    })),
  };
}

/*
 * Return a copy of the generated deck with permanent
 * one-based positions assigned.
 *
 * These positions become part of the deck identity and
 * remain stable for this generated deck.
 */
function assignDeckPositions(cards) {
  return cards.map((card, index) => ({
    deck_position: index + 1,
    ...card,
  }));
}

/*
 * Generate a secure UUID for one manifest instance.
 *
 * The deterministic Deck ID identifies the generated deck
 * configuration and card order. This UUID uniquely identifies
 * this particular generation event and downloaded manifest.
 */
function createDeckUuid() {
  if (
    !globalThis.crypto ||
    typeof globalThis.crypto.randomUUID !== "function"
  ) {
    throw new Error(
      "Secure UUID generation is not available in this browser context.",
    );
  }

  return globalThis.crypto.randomUUID();
}

/* ---------------------------------------------------------
 * Generation transaction
 * --------------------------------------------------------- */

/*
 * Generate one playable deck from the current builder state.
 *
 * The operation either completes with a matching generated
 * deck and manifest or reports a failure without exposing
 * partially generated output.
 */
async function generateDeck() {
  /*
   * Read and validate the requested configuration.
   */
  try {
    const editions = getSelectedOptionValues("edition");
    const categories = getSelectedOptionValues("category");

    const requested = validateDeckSize(ui.deckSizeInput.value);

    const seed = validateSeed(ui.seedInput.value);

    /*
     * Require at least one edition and one category.
     */
    if (editions.length === 0 || categories.length === 0) {
      setStatus("Select at least one edition and one category.");

      return;
    }

    /*
     * Find active, approved cards matching both the selected
     * edition set and category set.
     */
    const eligible = state.cards.filter((card) =>
      cardMatchesSelection(card, editions, categories),
    );

    /*
     * Clear stale output when the current configuration has no
     * playable cards.
     */
    if (eligible.length === 0) {
      clearGeneratedOutput();

      setStatus("No cards match the selected editions and categories.");

      return;
    }

    /*
     * Select cards deterministically without mutating the
     * validated catalog order.
     */
    const chosen = seededShuffle(eligible, seed).slice(
      0,
      Math.min(requested, eligible.length),
    );

    /*
     * Assign a unique manifest-instance UUID in addition to the
     * deterministic Deck ID and fingerprint.
     */
    const deckUuid = createDeckUuid();

    const { deckId, fingerprint } = await createDeckIdentity({
      seed,
      editions,
      categories,
      requestedCardCount: requested,
      cards: chosen,
    });

    /*
     * Preserve permanent one-based positions for this generated
     * deck.
     */
    state.generated = assignDeckPositions(chosen);

    /*
     * Capture the generation configuration and immutable card
     * content snapshots needed to identify or reproduce the deck.
     */
    state.manifest = buildManifest({
      deckUuid,
      deckId,
      fingerprint,
      seed,
      editions,
      categories,
      requested,
      generated: state.generated,
    });

    /*
     * Report whether the requested deck size was fully satisfied.
     */
    setStatus(
      chosen.length < requested
        ? `Only ${chosen.length} eligible cards were available.`
        : `Generated ${chosen.length} playable cards.`,
    );

    /*
     * Render preview and print output from the same generated
     * deck state.
     */
    renderOutput();
  } catch (error) {
    /*
     * Fail visibly without exposing an uncaught generation error
     * to the user.
     */
    console.error(error);

    setStatus(
      error instanceof Error
        ? error.message
        : "The deck could not be generated.",
    );
  }
}

