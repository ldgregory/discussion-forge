/* ---------------------------------------------------------
 * Card-pack lookup
 * --------------------------------------------------------- */

/*
 * Return an installed card-pack definition by ID.
 *
 * Rejecting unknown IDs prevents callers from constructing
 * arbitrary resource paths.
 */
function requireCardPack(cardPackId) {
  const cardPack = CARD_PACK_REGISTRY.packs.find(
    (registeredCardPack) => registeredCardPack.id === cardPackId,
  );

  if (!cardPack) {
    throw new Error(`Unsupported card pack: ${cardPackId}`);
  }

  return cardPack;
}

/* ---------------------------------------------------------
 * JSON transport
 * --------------------------------------------------------- */

/*
 * Fetch one local JSON resource.
 *
 * Catalog requests use same-origin credentials and bypass
 * the browser cache so development changes are not masked by
 * stale data.
 */
async function fetchJson(path) {
  const response = await fetch(path, {
    credentials: "same-origin",
    cache: "no-store",
  });

  if (!response.ok) {
    throw new Error(`Unable to load ${path}: HTTP ${response.status}.`);
  }

  return response.json();
}

/* ---------------------------------------------------------
 * Card-pack loading
 * --------------------------------------------------------- */

/*
 * Load and validate one registered card pack.
 *
 * The returned data is fully validated but is not published
 * to application state.
 */
async function loadCardPack(cardPackId) {
  const registeredCardPack = requireCardPack(cardPackId);

  /*
   * Fetch all pack resources concurrently.
   */
  const [rawPackManifest, rawCards, rawCategories, rawEditions] =
    await Promise.all([
      fetchJson(registeredCardPack.paths.manifest),
      fetchJson(registeredCardPack.paths.cards),
      fetchJson(registeredCardPack.paths.categories),
      fetchJson(registeredCardPack.paths.editions),
    ]);

  /*
   * Validate card-pack metadata consumed by the runtime.
   */
  const cardPack = validateCardPackManifest(rawPackManifest);

  if (cardPack.id !== registeredCardPack.id) {
    throw new Error(
      `Card-pack manifest ID "${cardPack.id}" does not match registered ID "${registeredCardPack.id}".`,
    );
  }

  /*
   * Reject packs that require a newer Discussion Forge
   * application version than the current runtime.
   */
  if (
    compareSemver(APPLICATION.version, cardPack.minimumApplicationVersion) < 0
  ) {
    throw new Error(
      `Card pack "${cardPack.id}" requires Discussion Forge ` +
        `${cardPack.minimumApplicationVersion} or later, but ` +
        `the current version is ${APPLICATION.version}.`,
    );
  }

  /*
   * Validate and normalize catalog records.
   */
  const categories = requireCatalogArray(
    rawCategories,
    "categories",
    LIMITS.maxCategories,
  ).map(validateCategory);

  const editions = requireCatalogArray(
    rawEditions,
    "editions",
    LIMITS.maxEditions,
  ).map(validateEdition);

  const cards = requireCatalogArray(rawCards, "cards", LIMITS.maxCards).map(
    validateCard,
  );

  /*
   * Validate relationships and uniqueness across the trusted
   * catalog records.
   */
  validateCatalogIntegrity(cards, categories, editions, cardPack);

  return {
    cardPack,

    catalog: {
      cards,
      categories,
      editions,
    },
  };
}

/* ---------------------------------------------------------
 * Card-pack activation
 * --------------------------------------------------------- */

/*
 * Load a registered card pack and publish its validated
 * catalog to application state.
 */
async function activateCardPack(cardPackId) {
  const { cardPack, catalog } = await loadCardPack(cardPackId);

  state.activeCardPack = cardPack;
  state.catalog = catalog;

  /*
   * Refresh controls whose available values depend on the
   * active card pack.
   */
  renderOptions();
}

