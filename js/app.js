/*
 * Download the generated deck manifest.
 *
 * The manifest contains the information required to identify
 * or reproduce the generated deck independently of the
 * printed cards.
 */
function downloadManifest() {
  if (!state.manifest) {
    setStatus("Generate a deck first.");

    return;
  }

  const blob = new Blob([JSON.stringify(state.manifest, null, 2)], {
    type: "application/json",
  });

  const url = URL.createObjectURL(blob);

  const anchor = document.createElement("a");

  anchor.href = url;

  anchor.download =
    `discussion-forge-${state.manifest.deck_id}` + "-manifest.json";

  anchor.hidden = true;

  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();

  window.setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 0);
}

